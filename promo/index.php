// Countdown Timer
function updateCountdown() {
    const now = new Date();
    const tomorrow = new Date(now);
    tomorrow.setDate(tomorrow.getDate() + 1);
    tomorrow.setHours(0, 0, 0, 0);
    
    const diff = tomorrow - now;
    
    const hours = Math.floor(diff / (1000 * 60 * 60));
    const minutes = Math.floor((diff % (1000 * 60 * 60)) / (1000 * 60));
    const seconds = Math.floor((diff % (1000 * 60)) / 1000);
    
    const h = String(hours).padStart(2, '0');
    const m = String(minutes).padStart(2, '0');
    const s = String(seconds).padStart(2, '0');
    
    // Pricing section countdown
    document.getElementById('hours').textContent = h;
    document.getElementById('minutes').textContent = m;
    document.getElementById('seconds').textContent = s;
    
    // Announcement bar countdown
    var aH = document.getElementById('abtH');
    var aM = document.getElementById('abtM');
    var aS = document.getElementById('abtS');
    if (aH) aH.textContent = h;
    if (aM) aM.textContent = m;
    if (aS) aS.textContent = s;

    // Order form countdown
    var ofH = document.getElementById('ofH');
    var ofM = document.getElementById('ofM');
    var ofS = document.getElementById('ofS');
    if (ofH) ofH.textContent = h;
    if (ofM) ofM.textContent = m;
    if (ofS) ofS.textContent = s;
}

