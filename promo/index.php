// ===== STICKY COUNTDOWN BAR =====
(function() {
    var stickyBar = document.getElementById('stickyCountdown');
    var pricingSection = document.getElementById('pricing');
    if (!stickyBar || !pricingSection) return;

    function checkSticky() {
        var rect = pricingSection.getBoundingClientRect();
        if (rect.bottom < 0) {
            stickyBar.classList.add('visible');
        } else {
            stickyBar.classList.remove('visible');
        }
    }

    var stickyTimeout;
    window.addEventListener('scroll', function() {
        clearTimeout(stickyTimeout);
        stickyTimeout = setTimeout(checkSticky, 50);
    });

    function updateStickyTimer() {
        var now = new Date();
        var tmr = new Date(now);
        tmr.setDate(tmr.getDate() + 1);
        tmr.setHours(0, 0, 0, 0);
        var diff = tmr - now;
        var h = Math.floor(diff / 3600000);
        var m = Math.floor((diff % 3600000) / 60000);
        var s = Math.floor((diff % 60000) / 1000);
        var hEl = document.getElementById('sctHours');
        var mEl = document.getElementById('sctMins');
        var sEl = document.getElementById('sctSecs');
        if (hEl) hEl.textContent = String(h).padStart(2, '0');
        if (mEl) mEl.textContent = String(m).padStart(2, '0');
        if (sEl) sEl.textContent = String(s).padStart(2, '0');
    }

    updateStickyTimer();
    setInterval(updateStickyTimer, 1000);
})();

