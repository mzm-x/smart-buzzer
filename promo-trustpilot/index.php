// ===== Daily countdown =====
(function() {
    function updateCountdown() {
        var now = new Date();
        var end = new Date(now);
        end.setHours(23, 59, 59, 999);
        var diff = end - now;
        if (diff < 0) diff = 0;
        var h = Math.floor(diff / 3600000);
        var m = Math.floor((diff % 3600000) / 60000);
        var s = Math.floor((diff % 60000) / 1000);
        var hE = document.getElementById('ofH');
        var mE = document.getElementById('ofM');
        var sE = document.getElementById('ofS');
        if (hE) hE.textContent = String(h).padStart(2, '0');
        if (mE) mE.textContent = String(m).padStart(2, '0');
        if (sE) sE.textContent = String(s).padStart(2, '0');
    }
    document.addEventListener('DOMContentLoaded', function() {
        updateCountdown();
        setInterval(updateCountdown, 1000);
    });
})();

// ===== submitOrder: full funnel =====
function submitOrder() {
    var biz = document.getElementById('ofBizName').value.trim();
    var wa = document.getElementById('ofWhatsapp').value.trim();
    var email = document.getElementById('ofEmail').value.trim();
    var pkg = document.querySelector('.of-pkg.selected');

    if (!biz) { alert('Please enter your Trustpilot business name.'); return; }
    if (!wa) { alert('Please enter your WhatsApp number.'); return; }
    if (!pkg) { alert('Please select a package.'); return; }

    var pkgName = pkg.querySelector('.of-pkg-name').textContent.replace(/POPULAR/g, '').trim();
    var pkgPrice = pkg.querySelector('.of-pkg-price').textContent.trim();
    var pkgValue = pkg.getAttribute('data-pkg');

    var meta = sbPkgMeta[pkgValue] || sbPkgMeta['growth'];
    var txnId = 'SB_' + Date.now() + '_' + Math.random().toString(36).substr(2, 6);

    var nameParts = biz.split(' ');
    var firstName = nameParts[0] || '';
    var lastName = nameParts.slice(1).join(' ') || '';

    // begin_checkout
    window.dataLayer = window.dataLayer || [];
    window.dataLayer.push({ecommerce: null});
    window.dataLayer.push({
        event: 'begin_checkout',
        user_data: {email: email || '', phone_number: wa, first_name: firstName, last_name: lastName},
        ecommerce: {
            currency: 'USD',
            value: meta.price,
            items: [{item_id: meta.id, item_name: meta.name, item_category: meta.item_category, price: meta.price, quantity: 1}]
        }
    });

    // add_payment_info
    window.dataLayer.push({ecommerce: null});
    window.dataLayer.push({
        event: 'add_payment_info',
        ecommerce: {
            currency: 'USD',
            value: meta.price,
            payment_type: 'Credit Card',
            items: [{item_id: meta.id, item_name: meta.name, item_category: meta.item_category, price: meta.price, quantity: 1}]
        }
    });

    // LocalStorage bridge for purchase event on thankyou.php
    localStorage.setItem('sb_user_email', email || '');
    localStorage.setItem('sb_user_phone', wa || '');
    localStorage.setItem('sb_user_fname', firstName || '');
    localStorage.setItem('sb_user_lname', lastName || '');
    localStorage.setItem('sb_txn_id', txnId);
    localStorage.setItem('sb_pkg', pkgValue);

    if (typeof fbq !== 'undefined') {
        fbq('track', 'InitiateCheckout', {value: meta.price, currency: 'USD', content_name: pkgName, content_type: 'product', content_ids: [pkgValue]});
    }
    if (typeof ttq !== 'undefined') {
        ttq.track('InitiateCheckout', {value: meta.price, currency: 'USD', content_name: pkgName});
    }

    logAnalyticsEvent('ORDER_SUBMIT', {package: pkgName, price: pkgPrice, business: biz, location: 'order_form'});

    fetch('log.php', {
        method: 'POST',
        headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({businessName: biz, whatsapp: wa, businessEmail: email, action: pkgValue.toUpperCase(), pageUrl: window.location.href})
    }).catch(function(err){ console.log('Customer log error:', err); });

    var fanbasisLinks = {
        'starter':     'https://www.fanbasis.com/agency-checkout/smartbuzzer/P1kLA',
        'growth':      'https://www.fanbasis.com/agency-checkout/smartbuzzer/RgmNV',
        'performance': 'https://www.fanbasis.com/agency-checkout/smartbuzzer/WnrVE'
    };
    var paymentUrl = fanbasisLinks[pkgValue];
    if (paymentUrl) {
        safeLocalStorage('set', 'sb_form_biz', '');
        safeLocalStorage('set', 'sb_form_wa', '');
        safeLocalStorage('set', 'sb_form_email', '');
        safeLocalStorage('set', 'sb_form_pkg', '');
        window.location.href = paymentUrl;
    }
}
