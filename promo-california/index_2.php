function v2CalcROI() {
    var industry = document.getElementById('v2roiIndustry').value;
    var revenue = parseInt(document.getElementById('v2roiRevenue').value) || 25000;

    // Industry multipliers (conservative ranges)
    var multipliers = {
        dental:     { custLow: 0.0006, custHigh: 0.0008, avgValue: 700 },
        hvac:       { custLow: 0.0005, custHigh: 0.0007, avgValue: 850 },
        restaurant: { custLow: 0.0012, custHigh: 0.0018, avgValue: 65 },
        auto:       { custLow: 0.0004, custHigh: 0.0006, avgValue: 600 },
        legal:      { custLow: 0.0002, custHigh: 0.0004, avgValue: 2500 },
        salon:      { custLow: 0.0010, custHigh: 0.0015, avgValue: 150 },
        health:     { custLow: 0.0005, custHigh: 0.0008, avgValue: 500 },
        other:      { custLow: 0.0005, custHigh: 0.0008, avgValue: 400 }
    };

    var m = multipliers[industry] || multipliers.other;
    var custLow = Math.max(8, Math.round(revenue * m.custLow));
    var custHigh = Math.max(12, Math.round(revenue * m.custHigh));
    var revLow = custLow * m.avgValue;
    var revHigh = custHigh * m.avgValue;
    var annualLow = revLow * 12;
    var annualHigh = revHigh * 12;
    var roiLow = (annualLow / 550).toFixed(1);
    var roiHigh = (annualHigh / 550).toFixed(1);

    document.getElementById('v2roiCustomers').textContent = '+' + custLow + ' to +' + custHigh;
    document.getElementById('v2roiRev').textContent = '+$' + revLow.toLocaleString() + ' – $' + revHigh.toLocaleString();
    document.getElementById('v2roiMultiple').textContent = roiLow + 'x – ' + roiHigh + 'x';
}
v2CalcROI();

