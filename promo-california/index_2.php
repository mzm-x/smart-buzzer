(function v2ExitIntent() {
    var shown = false;
    var overlay = document.getElementById('v2ExitOverlay');
    if (!overlay) return;

    // Don't show if user already saw it this session
    if (sessionStorage.getItem('v2ExitShown') === '1') return;

    function showExit() {
        if (shown) return;
        shown = true;
        sessionStorage.setItem('v2ExitShown', '1');
        overlay.classList.add('active');
        document.body.style.overflow = 'hidden';
        startExitCountdown();
        // Track
        logAnalyticsEvent('EXIT_INTENT_SHOWN', {});
        window.dataLayer = window.dataLayer || [];
        window.dataLayer.push({ event: 'exit_intent_popup_shown' });
    }

    // Desktop: trigger on mouseleave from top
    document.addEventListener('mouseleave', function(e) {
        if (e.clientY <= 0 && !shown) {
            showExit();
        }
    });

    // Mobile: trigger on scroll-up after deep scroll
    var lastScroll = 0;
    var deepScrolled = false;
    window.addEventListener('scroll', function() {
        var s = window.scrollY;
        if (s > 800) deepScrolled = true;
        if (deepScrolled && s < lastScroll - 200 && !shown) {
            // Aggressive scroll-up detected
            showExit();
        }
        lastScroll = s;
    });

    // Fallback: trigger after 60 sec if user idle on page
    setTimeout(function() { if (!shown) showExit(); }, 60000);

    // Coupon countdown
    var couponSec = 15 * 60;
    function startExitCountdown() {
        var minEl = document.getElementById('v2ExitMin');
        var secEl = document.getElementById('v2ExitSec');
        if (!minEl || !secEl) return;
        var iv = setInterval(function() {
            if (couponSec <= 0) { clearInterval(iv); return; }
            couponSec--;
            var m = Math.floor(couponSec / 60);
            var s = couponSec % 60;
            minEl.textContent = String(m).padStart(2, '0');
            secEl.textContent = String(s).padStart(2, '0');
        }, 1000);
    }
})();

